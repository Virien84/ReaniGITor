package io.github.virien84.reanigitor;

import java.io.IOException;
import java.io.InputStream;
import java.io.PrintStream;
import java.util.Properties;
import java.util.regex.Pattern;

/** Command-line entry point: holds a Día de los Muertos wake for a user's abandoned repos. */
public final class ReaniGITor {

    static final int OK = 0;
    static final int FAILURE = 1;
    static final int USAGE_ERROR = 2;

    private static final String USAGE = """
            Usage: reanigitor <github-username>
                   reanigitor --help | --version

            Finds the abandoned repositories of a GitHub user and writes a cemetery
            for them, with texts generated by a local Gemma model (Ollama).
            """;

    // GitHub rules: 1-39 alphanumerics or single hyphens, no hyphen at either end.
    private static final Pattern GITHUB_USERNAME =
            Pattern.compile("[A-Za-z0-9](?:[A-Za-z0-9]|-(?=[A-Za-z0-9])){0,38}");

    private ReaniGITor() {
    }

    public static void main(String[] args) {
        System.exit(run(args, System.out, System.err));
    }

    static int run(String[] args, PrintStream out, PrintStream err) {
        if (args.length != 1) {
            err.print(USAGE);
            return USAGE_ERROR;
        }
        String arg = args[0];
        switch (arg) {
            case "--help", "-h" -> {
                out.print(USAGE);
                return OK;
            }
            case "--version", "-V" -> {
                out.println("ReaniGITor " + version());
                return OK;
            }
            default -> {
                // Fall through to the username checks below.
            }
        }
        if (arg.startsWith("-")) {
            err.println("Unknown option: " + arg);
            err.print(USAGE);
            return USAGE_ERROR;
        }
        if (!GITHUB_USERNAME.matcher(arg).matches()) {
            err.println("Not a valid GitHub username: " + arg);
            return USAGE_ERROR;
        }
        err.println("Nothing to bury yet: the pipeline for " + arg + " is still being dug.");
        return FAILURE;
    }

    static String version() {
        Properties props = new Properties();
        try (InputStream in = ReaniGITor.class.getResourceAsStream("/reanigitor.properties")) {
            if (in != null) {
                props.load(in);
            }
        } catch (IOException e) {
            // Fall back to "unknown" below.
        }
        return props.getProperty("version", "unknown");
    }
}
