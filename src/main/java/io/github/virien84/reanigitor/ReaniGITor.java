package io.github.virien84.reanigitor;

import io.github.virien84.reanigitor.github.AbandonmentPolicy;
import io.github.virien84.reanigitor.github.GitHubClient;
import io.github.virien84.reanigitor.github.GitHubException;
import io.github.virien84.reanigitor.github.Remains;
import io.github.virien84.reanigitor.github.Repo;
import java.io.IOException;
import java.io.InputStream;
import java.io.PrintStream;
import java.net.URI;
import java.time.Clock;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneOffset;
import java.util.List;
import java.util.Properties;

/** Command-line entry point: holds a Día de los Muertos wake for a user's abandoned repos. */
public final class ReaniGITor {

    static final int OK = 0;
    static final int FAILURE = 1;
    static final int USAGE_ERROR = 2;

    private static final String USAGE = """
            Usage: reanigitor <github-username> [--months N] [--max N]
                   reanigitor --help | --version

            Finds the abandoned repositories of a GitHub user and writes a cemetery
            for them, with texts generated by a local Gemma model (Ollama).

              --months N   a repo is abandoned after N months without a push (default 12)
              --max N      bury at most N repos, the longest dead first (default 12)

            GITHUB_TOKEN (environment or .env) is optional: it raises the GitHub API
            limit from 60 to 5,000 requests per hour.
            """;

    private ReaniGITor() {
    }

    public static void main(String[] args) {
        System.exit(run(args, System.out, System.err));
    }

    static int run(String[] args, PrintStream out, PrintStream err) {
        if (args.length == 1 && (args[0].equals("--help") || args[0].equals("-h"))) {
            out.print(USAGE);
            return OK;
        }
        if (args.length == 1 && (args[0].equals("--version") || args[0].equals("-V"))) {
            out.println("ReaniGITor " + version());
            return OK;
        }
        return run(args, out, err, GitHubClient.DEFAULT_API, Env.load().get("GITHUB_TOKEN"), Clock.systemUTC());
    }

    static int run(String[] args, PrintStream out, PrintStream err, URI githubApi, String githubToken, Clock clock) {
        Options options;
        try {
            options = Options.parse(args);
        } catch (UsageException e) {
            if (args.length > 0) {
                err.println(e.getMessage());
            }
            err.print(USAGE);
            return USAGE_ERROR;
        }
        try {
            GitHubClient github = new GitHubClient(githubApi, githubToken);
            AbandonmentPolicy policy = new AbandonmentPolicy(options.months(), clock);

            out.printf("Exhuming %s's repos (abandoned = no push in %d months)...%n",
                    options.user(), options.months());
            List<Repo> repos = github.listRepos(options.user());
            long abandoned = repos.stream().filter(policy::isAbandoned).count();
            List<Repo> chosen = policy.select(repos, options.max());
            out.printf("%d repos, %d abandoned.%n", repos.size(), abandoned);
            if (chosen.isEmpty()) {
                out.println("No abandoned repos. Everyone here is alive and well... for now.");
                return OK;
            }
            if (chosen.size() < abandoned) {
                out.printf("Digging up the %d longest dead.%n", chosen.size());
            }
            for (Repo repo : chosen) {
                printRemains(out, github.exhume(repo));
            }
            return OK;
        } catch (GitHubException e) {
            err.println(e.getMessage());
            return FAILURE;
        }
    }

    private static void printRemains(PrintStream out, Remains remains) {
        Repo repo = remains.repo();
        out.println();
        out.printf("RIP %s  (%s - %s)%n", repo.name(), day(repo.createdAt()), day(repo.lastSignOfLife()));
        out.printf("    %s, %d stars, %d forks, %d open issues%s%n",
                repo.language() == null ? "no language" : repo.language(),
                repo.stars(), repo.forks(), repo.openIssues(), repo.archived() ? ", archived" : "");
        if (repo.description() != null) {
            out.println("    " + Text.firstLine(repo.description(), 100));
        }
        if (remains.lastCommitMessage() != null) {
            out.printf("    Last words (%s): %s%n", day(remains.lastCommitAt()), remains.lastCommitMessage());
        }
        out.printf("    README: %s%n", remains.readme() == null ? "none"
                : remains.readme().length() + " characters");
        for (String issue : remains.openIssueTitles()) {
            out.println("    Unfinished business: " + issue);
        }
    }

    private static String day(Instant instant) {
        return instant == null ? "?" : LocalDate.ofInstant(instant, ZoneOffset.UTC).toString();
    }

    static String version() {
        Properties props = new Properties();
        try (InputStream in = ReaniGITor.class.getResourceAsStream("/reanigitor.properties")) {
            if (in != null) {
                props.load(in);
            }
        } catch (IOException e) {
            // Fall back to "unknown" below.
        }
        return props.getProperty("version", "unknown");
    }
}
