package io.github.virien84.reanigitor;

import io.github.virien84.reanigitor.cemetery.Cemetery;
import io.github.virien84.reanigitor.github.AbandonmentPolicy;
import io.github.virien84.reanigitor.github.GitHubClient;
import io.github.virien84.reanigitor.github.GitHubException;
import io.github.virien84.reanigitor.github.Remains;
import io.github.virien84.reanigitor.github.Repo;
import io.github.virien84.reanigitor.ollama.JsonChat;
import io.github.virien84.reanigitor.ollama.OllamaClient;
import io.github.virien84.reanigitor.ollama.OllamaException;
import io.github.virien84.reanigitor.wake.Grave;
import io.github.virien84.reanigitor.wake.Graveyard;
import io.github.virien84.reanigitor.wake.Undertaker;
import java.io.FileDescriptor;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.PrintStream;
import java.net.URI;
import java.nio.charset.Charset;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.List;
import java.util.Properties;
import java.util.function.Function;

/** Command-line entry point: holds a Día de los Muertos wake for a user's abandoned repos. */
public final class ReaniGITor {

    static final int OK = 0;
    static final int FAILURE = 1;
    static final int USAGE_ERROR = 2;

    private static final String USAGE = """
            Usage: reanigitor <github-username> [options]
                   reanigitor --help | --version

            Finds the abandoned repositories of a GitHub user and writes a cemetery
            for them, with texts generated by a local Gemma model (Ollama).

              --months N     a repo is abandoned after N months without a push (default 12)
              --max N        bury at most N repos, the longest dead first (default 12)
              --lang en|es   language of the calaveritas (default en)
              --model NAME   Ollama model (default gemma4:e4b-it-qat)
              --out DIR      output folder (default output)
              --redraw       draw the cemetery again from the saved graves.json,
                             without calling GitHub or the model

            GITHUB_TOKEN (environment or .env) is optional: it raises the GitHub API
            limit from 60 to 5,000 requests per hour.
            """;

    private ReaniGITor() {
    }

    public static void main(String[] args) {
        // Java 17 writes in the platform charset (Cp1252 on Windows), which mangles accents and
        // emoji: use the console's own charset, or UTF-8 when the output is redirected.
        Charset charset = System.console() != null ? System.console().charset() : StandardCharsets.UTF_8;
        PrintStream out = new PrintStream(new FileOutputStream(FileDescriptor.out), true, charset);
        PrintStream err = new PrintStream(new FileOutputStream(FileDescriptor.err), true, charset);
        System.exit(run(args, out, err));
    }

    static int run(String[] args, PrintStream out, PrintStream err) {
        if (args.length == 1 && (args[0].equals("--help") || args[0].equals("-h"))) {
            out.print(USAGE);
            return OK;
        }
        if (args.length == 1 && (args[0].equals("--version") || args[0].equals("-V"))) {
            out.println("ReaniGITor " + version());
            return OK;
        }
        return run(args, out, err, GitHubClient.DEFAULT_API, Env.load().get("GITHUB_TOKEN"),
                Clock.systemUTC(), ReaniGITor::localModel);
    }

    private static JsonChat localModel(String model) {
        OllamaClient ollama = new OllamaClient(OllamaClient.DEFAULT_URL, model);
        ollama.requireModel();
        return ollama;
    }

    /**
     * @param models opens the model by name, failing with an {@link OllamaException} when it is
     *               not available
     */
    static int run(String[] args, PrintStream out, PrintStream err, URI githubApi, String githubToken,
            Clock clock, Function<String, JsonChat> models) {
        Options options;
        try {
            options = Options.parse(args);
        } catch (UsageException e) {
            if (args.length > 0) {
                err.println(e.getMessage());
            }
            err.print(USAGE);
            return USAGE_ERROR;
        }
        Path dir = options.out().resolve(options.user());
        if (options.redraw()) {
            return redraw(dir, out, err);
        }
        try {
            GitHubClient github = new GitHubClient(githubApi, githubToken);
            AbandonmentPolicy policy = new AbandonmentPolicy(options.months(), clock);

            out.printf("Exhuming %s's repos (abandoned = no push in %d months)...%n",
                    options.user(), options.months());
            List<Repo> repos = github.listRepos(options.user());
            long abandoned = repos.stream().filter(policy::isAbandoned).count();
            List<Repo> chosen = policy.select(repos, options.max());
            out.printf("%d repos, %d abandoned.%n", repos.size(), abandoned);
            if (chosen.isEmpty()) {
                out.println("No abandoned repos. Everyone here is alive and well... for now.");
                return OK;
            }
            if (chosen.size() < abandoned) {
                out.printf("Burying the %d longest dead.%n", chosen.size());
            }

            Undertaker undertaker = new Undertaker(models.apply(options.model()), options.lang(), clock);
            out.printf("The coroner is %s, running locally. This takes a while.%n", options.model());
            List<Grave> graves = new ArrayList<>();
            for (int i = 0; i < chosen.size(); i++) {
                Repo repo = chosen.get(i);
                out.printf("%n[%d/%d] %s%n", i + 1, chosen.size(), repo.name());
                Instant start = clock.instant();
                Remains remains = github.exhume(repo);
                Grave grave = undertaker.bury(remains);
                graves.add(grave);
                printGrave(out, grave, Duration.between(start, Instant.now(clock)));
            }

            Graveyard graveyard = new Graveyard(options.user(), clock.instant(), options.months(),
                    options.model(), options.lang(), graves);
            graveyard.write(dir.resolve(Graveyard.FILE_NAME));
            Path page = Cemetery.write(graveyard, dir);
            out.printf("%nBuried %d repos. Open the cemetery: %s%n", graves.size(), page.toAbsolutePath());
            return OK;
        } catch (GitHubException | OllamaException e) {
            err.println(e.getMessage());
            return FAILURE;
        } catch (IOException e) {
            err.println("Could not write the graveyard: " + e.getMessage());
            return FAILURE;
        }
    }

    private static int redraw(Path dir, PrintStream out, PrintStream err) {
        Path file = dir.resolve(Graveyard.FILE_NAME);
        if (!Files.isRegularFile(file)) {
            err.println("There is no " + file + " to redraw. Run it once without --redraw.");
            return FAILURE;
        }
        try {
            Path page = Cemetery.write(Graveyard.read(file), dir);
            out.println("Cemetery redrawn: " + page.toAbsolutePath());
            return OK;
        } catch (IOException e) {
            err.println("Could not redraw the cemetery: " + e.getMessage());
            return FAILURE;
        }
    }

    private static void printGrave(PrintStream out, Grave grave, Duration took) {
        Repo repo = grave.remains().repo();
        out.printf("RIP %s  (%s - %s)%n", repo.name(), day(repo.createdAt()), day(repo.lastSignOfLife()));
        out.println("  Cause of death: " + grave.autopsy().causeOfDeath());
        out.println("  Epitaph: " + grave.autopsy().epitaph());
        out.println("  Calaverita: " + grave.calaverita().title());
        grave.calaverita().verses().forEach(verse -> out.println("    " + verse));
        out.println("  Resurrection prophecy:");
        List<String> steps = grave.autopsy().resurrection();
        for (int i = 0; i < steps.size(); i++) {
            out.printf("    %d. %s%n", i + 1, steps.get(i));
        }
        if (grave.autopsy().fallback() || grave.calaverita().fallback()) {
            out.println("  (the model did not answer properly; stock text used)");
        }
        if (!took.isZero()) {
            out.printf("  (%d s)%n", took.toSeconds());
        }
    }

    private static String day(Instant instant) {
        return instant == null ? "?" : LocalDate.ofInstant(instant, ZoneOffset.UTC).toString();
    }

    static String version() {
        Properties props = new Properties();
        try (InputStream in = ReaniGITor.class.getResourceAsStream("/reanigitor.properties")) {
            if (in != null) {
                props.load(in);
            }
        } catch (IOException e) {
            // Fall back to "unknown" below.
        }
        return props.getProperty("version", "unknown");
    }
}
